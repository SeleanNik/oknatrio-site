export const brandList = Object.values(brands);
export const brandsOf = (parent) => brandList.filter((b) => b.parent === parent);

// Типы конструкций бренда (окна, двери, фасады…) из разделов; у «окон» — переключатель систем профиля.
// Тексты, карточки и вопросы, изменённые в админке (public/data/pages.json), перекрывают черновые из этого файла.
const lines = (v) => (Array.isArray(v) ? v : String(v || '').split('\n')).map((x) => String(x).trim()).filter(Boolean);
export const typesOf = (b) => {
  const r = razdely[b.parent];
  const list = r.typesByBrand?.[b.name] ?? r.types;
  const ed = pagesData[b.id] || {};
  return list.map((t) => {
    let sys = b.systemsByType?.[t.id] ?? (t.id === 'okna' ? b.systems : undefined);
    const own = ed.cards?.[t.id];
    if (Array.isArray(own) && own.length) sys = own.map((c) => ({ id: c.id, name: c.name, tag: c.tag || '', text: c.text || '', image: c.image || '', specs: lines(c.specs) }));
    if (sys) return { ...t, systems: sys };
    const p = (ed.plain || []).find((x) => x.id === t.id);
    return p ? { ...t, text: p.text || t.text, points: p.specs ? lines(p.specs) : t.points, src: p.image || t.src } : t;
  });
};

// Заголовок, подзаголовок и вопросы страницы бренда
export const brandView = (b) => {
  const ed = pagesData[b.id] || {};
  return { ...b, h1: ed.h1 || b.h1, lead: ed.lead || b.lead, faq: Array.isArray(ed.faq) ? ed.faq.filter((f) => f.q) : b.faq };
};

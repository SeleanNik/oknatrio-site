export const brandList = Object.values(brands);
export const brandsOf = (parent) => brandList.filter((b) => b.parent === parent);

// Типы конструкций бренда (окна, двери, фасады…) из разделов; у «окон» — переключатель систем профиля.
export const typesOf = (b) => {
  const r = razdely[b.parent];
  const list = r.typesByBrand?.[b.name] ?? r.types;
  return list.map((t) => (t.id === 'okna' ? { ...t, systems: b.systems } : t));
};

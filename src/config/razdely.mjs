// Меню строится по видам: ссылка = страница раздела + якорь вида
export const typeLinks = (r) => r.types.map((t) => [t.title, `${r.path}#${t.id}`]);

// Тексты, виды, характеристики и FAQ можно менять из админки (public/data/pages.json): накладываем поверх значений выше.
const toType = (t) => ({
  id: t.id, title: t.title, text: t.text, images: t.images || [], src: (t.images || [])[0], alt: t.title,
  points: String(t.points || '').split('\n').map((x) => x.trim()).filter(Boolean),
});
const applyPage = (key, r) => {
  const p = pagesData[key];
  r.key = key;
  if (!p) return;
  if (Array.isArray(p.h1) && p.h1.length) r.h1 = p.h1.join('|');
  if (p.lead) r.lead = p.lead;
  if (Array.isArray(p.specs)) r.specs = p.specs;
  if (Array.isArray(p.faq)) r.faq = p.faq;
  if (Array.isArray(p.types)) r.types = p.types.map(toType);
  if (p.typesByBrand) {
    r.typesByBrand = Object.fromEntries(Object.entries(p.typesByBrand).map(([b, arr]) => [b, arr.map(toType)]));
    r.types = r.typesByBrand[r.brands[0]] ?? r.types; // меню и ссылки строятся по первому бренду
  }
};
applyPage('alyuminievye', razdely.alyuminievye);
applyPage('pvh', razdely.pvh);
